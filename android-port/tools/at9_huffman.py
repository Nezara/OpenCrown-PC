# Generates src/codec/at9_huffman.inc: the ATRAC9 Huffman codebooks (code lengths, codes and shape of each book).
# These are constants of the ATRAC9 bitstream format; the values are taken from LibAtrac9's huffCodes.c
# (Copyright (c) 2018 Alex Barney, MIT License, https://github.com/Thealexbarney/LibAtrac9). Only the data is used.
#
#   python tools/at9_huffman.py <LibAtrac9/C/src/huffCodes.c> src/codec/at9_huffman.inc
import re
import sys

src = open(sys.argv[1], encoding='utf-8').read()

arrays = {}
for m in re.finditer(r'static const uint(?:8|16)_t (\w+)\[(\d+)\]\s*=\s*\{([^}]*)\}', src):
    vals = [int(v, 0) for v in m.group(3).replace('\n', ' ').split(',') if v.strip()]
    assert len(vals) == int(m.group(2)), m.group(1)
    arrays[m.group(1)] = vals


def book(entry):
    # {Bits, Codes, Lookup, Length, ValueCount, ValueCountPower, ValueBits, ValueMax, MaxBitSize} or {0}
    parts = [p.strip() for p in entry.split(',')]
    if parts == ['0']:
        return None
    bits, codes, _lookup, length, vc, vcp, vb, vmax, maxbits = parts
    return bits[:-4], int(length), int(vc), int(vcp), int(vb), int(vmax), int(maxbits)


def books_of(name):
    m = re.search(name + r'\[[^=]*=\s*\{(.*?)\n\};', src, re.S)
    return [book(e) for e in re.findall(r'\{([^{}]*)\}', m.group(1))]


out = ['// Generated by tools/at9_huffman.py - do not edit.',
       '// ATRAC9 Huffman codebooks (bitstream format constants). Values from LibAtrac9 huffCodes.c,',
       '// Copyright (c) 2018 Alex Barney, MIT License (https://github.com/Thealexbarney/LibAtrac9).',
       '// Book = {name, entries, values per code, log2 of that, bits per value, value range, longest code}.',
       '']
emitted = set()
for name, vals in arrays.items():
    kind = 'uint8_t' if name.endswith('Bits') else 'uint16_t'
    out.append('static const %s k%s[%d] = {%s};' % (kind, name, len(vals), ', '.join(str(v) for v in vals)))
out.append('')


def emit_books(cname, books):
    out.append('static const BookDef %s[%d] = {' % (cname, len(books)))
    for b in books:
        if b is None:
            out.append('    {},')
        else:
            n, length, vc, vcp, vb, vmax, maxbits = b
            out.append('    {k%sBits, k%sCodes, %d, %d, %d, %d, %d, %d},' % (n, n, length, vc, vcp, vb, vmax, maxbits))
    out.append('};')


emit_books('kSfUnsignedBooks', books_of('HuffmanScaleFactorsUnsigned'))
emit_books('kSfSignedBooks', books_of('HuffmanScaleFactorsSigned'))
spec = books_of('HuffmanSpectrum')
# HuffmanSpectrum[2][8][4]: the {{0}} rows for precisions 0 and 1 flatten to a single empty entry each.
flat = []
it = iter(re.findall(r'\{\{0\}\}|\{[^{}]*\}', re.search(r'HuffmanSpectrum\[[^=]*=\s*\{(.*?)\n\};', src, re.S).group(1)))
for tok in it:
    if tok == '{{0}}':
        flat.extend([None] * 4)
    else:
        flat.append(book(tok[1:-1]))
assert len(flat) == 64, len(flat)
emit_books('kSpectrumBooks', flat)  # [set * 32 + precision * 4 + codebook index]
open(sys.argv[2], 'w', newline='\n').write('\n'.join(out) + '\n')
print('wrote', sys.argv[2], len(arrays), 'arrays')
