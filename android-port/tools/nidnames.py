"""Builds data/nids.txt: names for the eboot's function imports, from the vitasdk vita-headers NID database (MIT).

    python nidnames.py <vita-headers>/db/360 <mobile_run --list-imports output> > data/nids.txt
    python nidnames.py --header data/nids.txt > src/hle/nids.h

The header gives HLE code one constant per imported function (NID_<name>), so registrations never carry a
hand-typed NID.

Only the NIDs the game imports are kept. The db is YAML; this reads just the
modules -> libraries -> functions mapping by indentation (no YAML dependency).
"""
import os
import re
import sys

KEY = re.compile(r'^( *)([A-Za-z0-9_]+):\s*(0x[0-9A-Fa-f]+)?\s*$')


def read_db(path):
    names = {}  # (library, nid) -> name
    for fn in sorted(os.listdir(path)):
        if not fn.endswith('.yml'):
            continue
        stack = []  # (indent, key)
        for line in open(os.path.join(path, fn), encoding='utf-8'):
            m = KEY.match(line.rstrip('\n'))
            if not m:
                continue
            indent, key, val = len(m.group(1)), m.group(2), m.group(3)
            while stack and stack[-1][0] >= indent:
                stack.pop()
            keys = [k for _, k in stack]
            if val and len(keys) >= 5 and keys[0] == 'modules' and keys[2] == 'libraries' and keys[4] in ('functions', 'variables'):
                names[(keys[3], int(val, 16))] = key
            stack.append((indent, key))
    return names


def header(path):
    print('// Generated by tools/nidnames.py --header from data/nids.txt. Do not edit.')
    print('// NID values: vitasdk vita-headers NID database, Copyright 2017 vitasdk, MIT License.')
    print('#pragma once')
    print('#include <cstdint>')
    print('namespace hle {')
    seen = set()
    for line in open(path, encoding='utf-8'):
        p = line.split()
        if len(p) != 2 or line.startswith('#') or p[1] in seen:
            continue
        seen.add(p[1])
        print('constexpr uint32_t NID_%s = 0x%s;' % (p[1], p[0]))
    print('}  // namespace hle')


def main():
    if sys.argv[1] == '--header':
        return header(sys.argv[2])
    db, listing = sys.argv[1], sys.argv[2]
    names = read_db(db)
    by_nid = {}
    for (lib, nid), name in names.items():
        by_nid.setdefault(nid, name)
    print('# NID names for the Dragon\'s Crown (Vita, PCSE00019 1.09) imports.')
    print('# Generated by tools/nidnames.py from the vitasdk vita-headers NID database (db/360),')
    print('# Copyright 2017 vitasdk, MIT License (https://github.com/vitasdk/vita-headers/blob/master/LICENSE.md).')
    missing = 0
    for line in open(listing, encoding='utf-8'):
        p = line.split()
        if len(p) < 3 or not p[0].startswith('8'):
            continue
        lib, nid = p[1], int(p[2], 16)
        name = names.get((lib, nid)) or by_nid.get(nid)
        if name:
            print('%08x %s' % (nid, name))
        else:
            missing += 1
            print('# %08x %s (not in db)' % (nid, lib))
    print('# %d not in db' % missing, file=sys.stderr)


if __name__ == '__main__':
    main()
