# Rebuilds the SDL_gpu shaders (src/render/shaders/*.vert|frag) into src/render/shaders/generated/*.h (checked in, so
# normal builds need no Vulkan SDK). Run after editing a shader:
#   powershell -ExecutionPolicy Bypass -File port\tools\build_shaders.ps1
# GLSL 450 -> SPIR-V (glslc) for Vulkan; SPIR-V -> HLSL SM 6.0 (spirv-cross, register spaces from the descriptor sets:
# SDL_gpu's DXIL convention) -> DXIL (dxc). DXIL must be signed or Windows 10's D3D12 runtime rejects it: dxc signs
# when dxil.dll sits next to it, so dxc runs from a temp copy with the Windows SDK's dxil.dll (the SDKs stay untouched).
param(
    [string]$VulkanSdk = "C:\VulkanSDK\1.4.363.0",
    [string]$DxilDll = "C:\Program Files (x86)\Windows Kits\10\bin\10.0.22621.0\x64\dxil.dll"
)
$ErrorActionPreference = "Stop"
$root = Split-Path -Parent (Split-Path -Parent $MyInvocation.MyCommand.Path)  # port/
$src = Join-Path $root "src\render\shaders"
$gen = Join-Path $src "generated"
$glslc = Join-Path $VulkanSdk "Bin\glslc.exe"
$spvc = Join-Path $VulkanSdk "Bin\spirv-cross.exe"
foreach ($f in @($glslc, $spvc, (Join-Path $VulkanSdk "Bin\dxc.exe"), (Join-Path $VulkanSdk "Bin\dxcompiler.dll"), $DxilDll)) {
    if (-not (Test-Path $f)) { throw "missing $f" }
}
$tmp = Join-Path ([IO.Path]::GetTempPath()) ("dcp_shaders_" + [Guid]::NewGuid().ToString("N"))
New-Item -ItemType Directory -Force $tmp | Out-Null
New-Item -ItemType Directory -Force $gen | Out-Null
try {
    Copy-Item (Join-Path $VulkanSdk "Bin\dxc.exe"), (Join-Path $VulkanSdk "Bin\dxcompiler.dll"), $DxilDll $tmp
    $dxc = Join-Path $tmp "dxc.exe"

    function Run($exe, [string[]]$a) {
        & $exe @a
        if ($LASTEXITCODE -ne 0) { throw "$exe failed ($LASTEXITCODE): $($a -join ' ')" }
    }
    function Write-Header($path, $name, [byte[]]$bytes, $comment) {
        $sb = New-Object System.Text.StringBuilder
        [void]$sb.AppendLine("// Generated by port/tools/build_shaders.ps1 from $comment. Do not edit.")
        [void]$sb.AppendLine("#pragma once")
        [void]$sb.AppendLine("static const unsigned char $name[$($bytes.Length)] = {")
        for ($i = 0; $i -lt $bytes.Length; $i += 24) {
            $n = [Math]::Min(24, $bytes.Length - $i)
            $line = ($bytes[$i..($i + $n - 1)] | ForEach-Object { "0x{0:x2}," -f $_ }) -join ""
            [void]$sb.AppendLine("    $line")
        }
        [void]$sb.AppendLine("};")
        [IO.File]::WriteAllText($path, $sb.ToString().Replace("`r`n", "`n"))
    }

    foreach ($s in Get-ChildItem $src -File | Where-Object { $_.Extension -in ".vert", ".frag" }) {
        $base = $s.BaseName + "_" + $s.Extension.TrimStart('.')       # main_vert
        $stage = if ($s.Extension -eq ".vert") { "vs_6_0" } else { "ps_6_0" }
        $spv = Join-Path $tmp "$base.spv"
        $hlsl = Join-Path $tmp "$base.hlsl"
        $dxil = Join-Path $tmp "$base.dxil"
        Run $glslc @("--target-env=vulkan1.0", "-O", $s.FullName, "-o", $spv)
        Run $spvc @("--hlsl", "--shader-model", "60", $spv, "--output", $hlsl)
        Run $dxc @("-nologo", "-T", $stage, "-E", "main", "-Fo", $dxil, $hlsl)
        $d = [IO.File]::ReadAllBytes($dxil)
        # DXBC container: "DXBC" then a 16-byte digest; all zero = unsigned (D3D12 on Windows 10 refuses it).
        if ([Text.Encoding]::ASCII.GetString($d, 0, 4) -ne "DXBC") { throw "$base.dxil: not a DXBC container" }
        if (-not ($d[4..19] | Where-Object { $_ -ne 0 })) { throw "$base.dxil is unsigned (dxil.dll not loaded by dxc)" }
        $id = ($base -split '_' | ForEach-Object { $_.Substring(0, 1).ToUpper() + $_.Substring(1) }) -join ""
        Write-Header (Join-Path $gen "$base.spv.h") "k${id}Spv" ([IO.File]::ReadAllBytes($spv)) "$($s.Name) (SPIR-V)"
        Write-Header (Join-Path $gen "$base.dxil.h") "k${id}Dxil" $d "$($s.Name) (DXIL SM 6.0, signed)"
        Copy-Item $hlsl (Join-Path $gen "$base.hlsl")  # for review only (what spirv-cross made of the GLSL)
        "{0}: SPIR-V {1} B, DXIL {2} B (signed)" -f $s.Name, (Get-Item $spv).Length, $d.Length
    }
} finally {
    Remove-Item -Recurse -Force $tmp -ErrorAction SilentlyContinue
}
